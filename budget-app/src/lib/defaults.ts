export function slug(s: string): string {
  return s.trim().replace(/\s+/g, '-').replace(/["'׳״()/,.]/g, '').slice(0, 60);
}

export function makeCategory(name: string, group: string, kind: CategoryKind): Category {
  return { id: `${kind}:${slug(group)}:${slug(name)}`, name, group, kind };
}

export const DEFAULT_CATEGORIES: Category[] = groups.flatMap(([group, kind, names]) =>
  names.map((n) => makeCategory(n, group, kind))
);


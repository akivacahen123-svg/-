/**
 * The family-finance course. It follows one family, the Barak family (Yael, Avi and four kids),
 * through a year of getting their money in order. Every lesson opens with a scene, explains the idea,
 * and ends with homework.
 */
export type Block =
  | { t: 'story'; text: string }
  | { t: 'h'; text: string }
  | { t: 'p'; text: string }
  | { t: 'list'; items: string[] }
  | { t: 'tip'; text: string }
  | { t: 'example'; title: string; text: string }
  | { t: 'stat'; value: string; text: string };

export interface Source {
  label: string;
  url: string;
}

export interface Lesson {
  id: string;
  title: string;
  minutes: number;
  blocks: Block[];
  quiz?: { q: string; options: string[]; answer: number; why: string };
  /** a concrete step to take in the app */
  action?: { text: string; page: 'dashboard' | 'transactions' | 'import' | 'budget' | 'wealth' };
  homework: string[];
  sources?: Source[];
}

export interface Module {
  id: string;
  title: string;
  intro: string;
  lessons: Lesson[];
}

